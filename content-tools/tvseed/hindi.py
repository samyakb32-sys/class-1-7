def _limit_options(ch, n):
    for q in ch["questions"]:
        if len(q["options"]) > n:
            correct = [o for o in q["options"] if o["correct"]]
            wrong = [o for o in q["options"] if not o["correct"]][: n - 1]
            q["options"] = correct + wrong
            # keep the original random order stable enough: correct answer is not always first
            q["options"].sort(key=lambda o: o["text"]["hi"])
    return ch
