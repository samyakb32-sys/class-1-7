def category_chapter(b, cid, title, blurb, icon, cats, difficulty=1):
    """cats: {key: (name L, [words])}. Two words from each category, distractors from the others."""
    items = []
    for key, (name, words) in cats.items():
        others = [w for k, (_, ws) in cats.items() if k != key for w in ws]
        for w in b.rnd.sample(words, 2):
            items.append((name, w, b.rnd.sample(others, 3)))
    ch = {"id": cid, "title": title, "blurb": blurb, "iconKey": icon, "questions": []}
    b.rnd.shuffle(items)
    for name, w, wr in items[:12]:
        opts = [{"text": S(w), "correct": True}] + [{"text": S(x), "correct": False} for x in wr]
        b.rnd.shuffle(opts)
        ch["questions"].append({
            "id": b.qid(cid),
            "prompt": L(f"Which word belongs to the group '{name['en']}'?", f"'{name['mr']}' या गटातील शब्द कोणता?", f"'{name['hi']}' वर्ग का शब्द कौन-सा है?"),
            "difficulty": difficulty,
            "hint": L(f"'{w}' belongs to the group '{name['en']}'.", f"'{w}' हा शब्द '{name['mr']}' या गटात येतो.", f"'{w}' शब्द '{name['hi']}' वर्ग में आता है।"),
            "options": opts,
        })
    return ch


def term_chapter(b, cid, title, blurb, icon, prompt, hint, rows, terms, count=12, difficulty=2):
    """rows: [(q, term_key)]; options are the translated grammar terms."""
    keys = list(terms.keys())
    ch = {"id": cid, "title": title, "blurb": blurb, "iconKey": icon, "questions": []}
    rows = list(rows)
    b.rnd.shuffle(rows)
    for q, k in rows[:count]:
        others = [kk for kk in keys if kk != k]
        b.rnd.shuffle(others)
        opts = [{"text": terms[k], "correct": True}] + [{"text": terms[o], "correct": False} for o in others[:3]]
        b.rnd.shuffle(opts)
        ans = terms[k]
        ch["questions"].append({
            "id": b.qid(cid),
            "prompt": L(*[prompt[lg].format(q=q) for lg in ("en", "mr", "hi")]),
            "difficulty": difficulty,
            "hint": L(*[hint[lg].format(q=q, a=ans[lg]) for lg in ("en", "mr", "hi")]),
            "options": opts,
        })
    return ch


def pairs(b, cid, title, blurb, icon, prompt, hint, rows, difficulty=2, bad=None, count=12):
    """rows: [(q, answer)]; distractors are the other answers."""
    return b.chapter(cid, title, blurb, icon, prompt, hint, [(q, a) for q, a in rows], pool=[a for _, a in rows], difficulty=difficulty, bad=bad, count=count)


